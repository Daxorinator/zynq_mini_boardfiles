m = json.load(open("ps7_model.json"))
out = ["/* GENERATED by gen_ddr_table.py from the reference model; DDRC register block, named fields, in the order the init applies it. */\n"]
ops = [o for o in m["ddr"] if o["op"] != "EXIT"]
for o in ops:
    a = o["args"]
    if o["op"] == "MASKWRITE" and 0xF8006000 <= a[0] < 0xF8007000:
        off = a[0] - 0xF8006000
        nm = NAMES.get(off, "ddrc_%03x" % off)
        out.append("\t/* %s (DDRC+%#x) */\n" % (nm, off))
        parts = []
        for f in o["fields"]:
            parts.append("FLD(%d, %d, %#x) /* %s */" % (f["hi"], f["lo"], f["val"], f["name"]))
        body = " |\n\t\t".join(parts) if parts else "0"
        out.append("\tREG_MASKW(DDRC_BASE + %#x, %#x,\n\t\t%s);\n" % (off, a[1], body))
    elif o["op"] == "MASKPOLL":
        out.append("\tif (REG_POLL(%#x, %#x)) return PS7_TIMEOUT;\n" % (a[0], a[1])) if False else out.append("\tREG_POLL(%#x, %#x);\n" % (a[0], a[1]))
open("ps7_ddr_table.inc", "w").write("".join(out))
print("ddr ops emitted:", sum(1 for o in ops if o["op"] == "MASKWRITE"))
